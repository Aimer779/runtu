import { readFile, mkdir, writeFile } from 'node:fs/promises';

const entries = [
  ['brushed-silver', '银色拉丝'],
  ['iridescent', '虹彩流光'],
  ['golden-rays', '金色光束'],
  ['prismatic-glass', '琉璃碎光'],
  ['pastel-marble', '彩色流纹'],
  ['orbital-glow', '星际弧光'],
  ['brushed-champagne', '香槟拉丝'],
];
const paths = process.argv.slice(2);
if (paths.length !== entries.length) {
  throw new Error('Pass seven PNG paths in the order documented in README.md.');
}
const signature = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]);
const backgrounds = await Promise.all(entries.map(async ([id, name], index) => {
  const bytes = await readFile(paths[index]);
  if (!bytes.subarray(0, 8).equals(signature)) {
    throw new Error(`Expected PNG: ${paths[index]}`);
  }
  return { id, name, src: `data:image/png;base64,${bytes.toString('base64')}` };
}));
// Data URLs keep Canvas exports origin-clean when the page is opened via file://.
const output = '// Generated by scripts/pack-backgrounds.mjs; preserves original PNG bytes.\n'
  + `const SOFTSHOT_BACKGROUNDS = ${JSON.stringify(backgrounds, null, 2)};\n`;
await mkdir(new URL('../assets/', import.meta.url), { recursive: true });
await writeFile(new URL('../assets/backgrounds.js', import.meta.url), output, 'utf8');
console.log(`Packed ${backgrounds.length} PNG backgrounds (${Buffer.byteLength(output)} bytes).`);
